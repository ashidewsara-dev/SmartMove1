CREATE TABLE drivers(
    driver_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_drivers PRIMARY KEY,
    driver_name VARCHAR(100) NOT NULL,
    licence_num VARCHAR(20) NOT NULL CONSTRAINT uq_drivers_licence UNIQUE,
    phone NUMBER(10) NOT NULL,
    experience VARCHAR(20) NOT NULL,
    availability VARCHAR (50) DEFAULT 'AVAILABLE' NOT NULL CONSTRAINT ck_drivers_availability
        CHECK (availability IN ('AVAILABLE', 'ON_TRIP', 'OFF DUTY'))
);

CREATE TABLE passengers(
    passenger_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_passengers PRIMARY KEY,
    passenger_name VARCHAR(100) NOT NULL,
    email VARCHAR (100) NOT NULL,
    joined_date DATE NOT NULL,
    bookings NUMBER NOT NULL,
    status VARCHAR (20) DEFAULT 'ACTIVE' NOT NULL CONSTRAINT ck_passengers_status
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE routes (
    route_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_routes PRIMARY KEY,
    origin VARCHAR(100) NOT NULL,
    destination VARCHAR (100) NOT NULL,
    distance VARCHAR(50) NOT NULL,
    duration VARCHAR(50) NOT NULL,
    fare VARCHAR (20) DEFAULT 'ACTIVE' NOT NULL
);


CREATE TABLE trips (
    trip_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_trips PRIMARY KEY,
    route_id NUMBER NOT NULL,
    vehicle_id NUMBER NOT NULL,
    driver_id NUMBER NOT NULL,
    trip_date DATE NOT NULL,
    departure_time DATE NOT NULL,
    seats NUMBER(3) NOT NULL,
    trip_status VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL CONSTRAINT ck_trips_status
        CHECK (trip_status IN ('SCHEDULED','IN_PROGRESS','COMPLETED','CANCELLED')),

    CONSTRAINT fk_trips_route FOREIGN KEY (route_id)REFERENCES routes(route_id),

    CONSTRAINT fk_trips_vehicle FOREIGN KEY (vehicle_id)REFERENCES vehicles(vehicle_id),

    CONSTRAINT fk_trips_driver FOREIGN KEY (driver_id)REFERENCES drivers(driver_id)
);


CREATE TABLE bookings (
    booking_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_bookings PRIMARY KEY,
    passenger_id NUMBER NOT NULL,
    trip_id NUMBER NOT NULL,
    traveled_date DATE NOT NULL,
    departure_time DATE NOT NULL,
    vehicle_id NUMBER NOT NULL,
    fare NUMBER NOT NULL,
    booking_status VARCHAR (50) NOT NULL CONSTRAINT ck_bookings_status
        CHECK (booking_status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'COMPLETED' )),
        
    CONSTRAINT fk_bookings_passenger FOREIGN KEY (passenger_id)REFERENCES passengers(passenger_id),
     CONSTRAINT fk_bookings_TRIP FOREIGN KEY (trip_id)REFERENCES trips(trip_id),
     CONSTRAINT fk_bookings_vehicle FOREIGN KEY (vehicle_id)REFERENCES vehicles(vehicle_id)
);


CREATE TABLE maintenance (
    maintenance_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_maintenance PRIMARY KEY,
    vehicle_id NUMBER NOT NULL,
    task VARCHAR2(50) NOT NULL,
    due_date DATE NOT NULL,
    cost NUMBER(10,2) DEFAULT 0 NOT NULL,
    maintenance_status VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL CONSTRAINT ck_maintenance_status
        CHECK (maintenance_status IN ('SCHEDULED', 'DUE SOON', 'OVERDUE','COMPLETED')),

    CONSTRAINT fk_maintenance_vehicle FOREIGN KEY (vehicle_id)REFERENCES vehicles(vehicle_id)

);


CREATE TABLE reviews (
    feedback_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_feedback PRIMARY KEY,
    passenger_id NUMBER NOT NULL,
    trip_id NUMBER NOT NULL,
    rating NUMBER(1) NOT NULL CONSTRAINT ck_feedback_rating CHECK (rating BETWEEN 1 AND 5),
    description VARCHAR (500) NOT NULL,

    CONSTRAINT fk_feedback_trip FOREIGN KEY (trip_id)REFERENCES trips(trip_id),
    CONSTRAINT fk_feedback_name FOREIGN KEY (passenger_id)REFERENCES passengers(passenger_id)
);

    
