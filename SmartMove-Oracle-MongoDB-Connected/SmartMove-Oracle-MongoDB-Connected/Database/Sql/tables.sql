CREATE TABLE vehicles (
    vehicle_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    vehicle_name VARCHAR2(100) NOT NULL,
    registration_plate VARCHAR2(20) NOT NULL,
    vehicle_type VARCHAR2(20) NOT NULL,
    seats NUMBER(3) NOT NULL,
    status VARCHAR2(15) DEFAULT 'ACTIVE' NOT NULL,
    odometer_km NUMBER(10) DEFAULT 0 NOT NULL
);
